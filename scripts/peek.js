const fs = require('fs'); const f = process.argv[2];
const d = JSON.parse(fs.readFileSync(`content/pages/${f}.json`, 'utf8'));
console.log(`# ${d.title} | ${d.path} | excerpt: ${d.excerpt}`);
d.blocks.forEach((b, i) => {
  const t = b.type;
  if (t === 'heading') console.log(`${i} H(${b.level}) ${b.text}`);
  else if (t === 'text') console.log(`${i} TEXT ${b.html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').slice(0, 260)}`);
  else if (t === 'list') console.log(`${i} LIST ${b.items.map(x => x.text).join(' | ').slice(0, 260)}`);
  else if (t === 'card') console.log(`${i} CARD ${b.title} :: ${b.text.slice(0, 120)} -> ${b.link}`);
  else if (t === 'button') console.log(`${i} BTN ${b.text} -> ${b.url}`);
  else if (t === 'image') console.log(`${i} IMG ${b.src.split('/').pop()} alt="${b.alt}"`);
  else if (t === 'background') console.log(`${i} BG ${b.src.split('/').pop()}${b.slideshow ? ' (slide)' : ''}`);
  else if (t === 'section_start') console.log(`${i} ---- section`);
  else if (t === 'form') console.log(`${i} FORM ${b.fields.map(f => f.label + (f.required ? '*' : '') + ':' + f.type).join(', ')} [${b.button}]`);
  else if (t === 'accordion') console.log(`${i} ACC ${b.items.map(x => x.title).join(' | ').slice(0, 200)}`);
  else if (t === 'hero_headline') console.log(`${i} HERO ${b.before} / ${b.rotating.join(' | ')}`);
  else if (t === 'counter') console.log(`${i} COUNT ${b.number}${b.suffix} ${b.title}`);
  else if (t === 'quote') console.log(`${i} QUOTE ${b.text.slice(0, 80)} - ${b.name}`);
  else console.log(`${i} ${t.toUpperCase()}`);
});
